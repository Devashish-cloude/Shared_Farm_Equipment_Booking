export type LanguageCode = 'en' | 'hi' | 'gu' | 'pa' | 'mr';

export interface LanguageOption {
  code: LanguageCode;
  label: string;
  nativeName: string;
  display: string;
}

export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'en', label: 'English', nativeName: 'English', display: 'English' },
  { code: 'hi', label: 'Hindi', nativeName: 'हिन्दी', display: 'हिन्दी (Hindi)' },
  { code: 'gu', label: 'Gujarati', nativeName: 'ગુજરાતી', display: 'ગુજરાતી (Gujarati)' },
  { code: 'pa', label: 'Punjabi', nativeName: 'ਪੰਜਾਬੀ', display: 'ਪੰਜਾਬੀ (Punjabi)' },
  { code: 'mr', label: 'Marathi', nativeName: 'मराठी', display: 'मराठी (Marathi)' },
];

export function normalizeLanguageCode(input: string): LanguageCode {
  if (!input) return 'en';
  const val = input.toLowerCase();
  if (val === 'hi' || val.includes('हिन्द') || val.includes('hindi')) return 'hi';
  if (val === 'gu' || val.includes('ગુજર') || val.includes('gujarat')) return 'gu';
  if (val === 'pa' || val.includes('ਪੰਜਾ') || val.includes('punjab')) return 'pa';
  if (val === 'mr' || val.includes('मराठ') || val.includes('marath')) return 'mr';
  return 'en';
}

